"""물건 종류(분류). 목록·검색 화면의 필터와 등록 화면의 선택지에 쓴다.

종류는 세 가지 방법으로 정해진다(앞의 것이 우선).
1. 등록하는 사람이 직접 고른다.
2. Claude가 사진을 보고 아래 목록에서 하나를 고른다(describe.py의 group).
3. 둘 다 없으면 메모나 Claude가 쓴 종류 이름에 든 낱말로 짐작한다(guess).
"""
import re
from typing import Literal, get_args

# 팀이 정한 8가지 (2026-11-17). 순서대로 화면에 보인다. Claude도 이 중에서만 고른다.
Group = Literal["의류", "전자기기", "학용품", "물병·텀블러", "가방·지갑", "액세서리", "운동용품", "기타"]
GROUPS = list(get_args(Group))

# 낱말로 짐작할 때 쓰는 단서. 위에서부터 먼저 맞는 종류로 정한다.
# (예: '노트북'은 전자기기가 먼저라서 학용품의 '노트'에 걸리지 않는다)
_CLUES = [
    ("물병·텀블러", "텀블러|물병|보온병|물통|보틀|머그"),
    ("전자기기", "이어폰|에어팟|버즈|헤드폰|헤드셋|충전기|케이블|보조배터리|휴대폰|핸드폰|스마트폰|아이폰|갤럭시|"
                 "태블릿|아이패드|노트북|마우스|USB|usb|스마트워치|전자"),
    ("의류", "체육복|후드|점퍼|패딩|자켓|재킷|조끼|티셔츠|셔츠|바지|치마|교복|가디건|니트|맨투맨|외투|코트|"
             "목도리|장갑|모자|양말|운동화|실내화|슬리퍼|신발|옷"),
    ("가방·지갑", "가방|백팩|파우치|지갑|에코백|크로스백|쇼핑백"),
    ("학용품", "필통|연필|볼펜|샤프|지우개|공책|노트|교과서|문제집|클리어파일|계산기|형광펜|사인펜|색연필|"
               "가위|수첩|다이어리|책"),
    ("운동용품", "축구공|농구공|배구공|야구공|탁구공|피구공|라켓|셔틀콕|줄넘기|글러브|헬멧|보호대|운동용품"),
    ("액세서리", "안경|선글라스|시계|목걸이|반지|팔찌|귀걸이|머리핀|머리끈|헤어핀|헤어밴드|키링|열쇠고리|인형|배지"),
]
_PATTERNS = [(group, re.compile(words)) for group, words in _CLUES]


def guess(text: str | None) -> str | None:
    """글에 든 낱말로 종류를 짐작한다. 아무 단서도 없으면 None(모름)."""
    if not text:
        return None
    for group, pattern in _PATTERNS:
        if pattern.search(text):
            return group
    return None


def clean(value: str | None) -> str | None:
    """화면에서 받은 종류가 목록에 있는 것인지 확인한다. 없거나 이상하면 None."""
    return value if value in GROUPS else None
